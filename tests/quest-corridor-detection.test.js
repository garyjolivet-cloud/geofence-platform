(function testProjectOnPathHintPicksNearbyLegOfAHairpin() {
  // A hairpin: down 200 m, across 6 m, back up 200 m -- the two legs are ~6 m
  // apart, so a point between them is near-equidistant from both. The hint
  // (where the previous fix was) must pick the leg the skier is on.
  const hairpin = { zoneId: "h", name: "Hairpin", runType: "run", widthM: 6,
    path: [[51.3020, -117.0500], [51.3002, -117.0500], [51.3002, -117.04991], [51.3020, -117.04991]],
    ref: [51.3011, -117.0500] };
  const G = QGeo.geom(hairpin);
  const p = [51.3010, -117.049955]; // between the legs, mid-way
  const nearFirst = QGeo.projectOnPath(p, G, 40);            // hint: early on the first leg
  const nearLast = QGeo.projectOnPath(p, G, G.L - 40);       // hint: late on the return leg
  assert(nearFirst.s < G.L / 2 && nearLast.s > G.L / 2, "hint disambiguates the hairpin's two legs, got " + nearFirst.s + " / " + nearLast.s);
})();


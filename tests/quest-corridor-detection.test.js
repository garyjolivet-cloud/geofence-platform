// on 09-18 within one minute: After Pride 8 s/49 m, Alley 17 14 s/60 m, South
// End Dump Run 17 s/65 m, each credited its full authored descent.
function blob(name, widthM, lengthM, lossM, lonOffsetM) {
  const lon = -117.05 + (lonOffsetM || 0) / QGeo.mPerDegLon(51.3005);
  const top = 51.3000 + lengthM / QGeo.mPerDegLat;
  return { zoneId: "rd-" + name, name, difficulty: "double-black", runType: "chute", activityType: "ski_chute",
    widthM, descentM: lossM, lengthM, path: [[top, lon], [51.3000, lon]], ref: [(top + 51.3000) / 2, lon] };
}
const afterPride = blob("After Pride", 75, 111, 81, 0);
const alley17 = blob("Alley 17", 50, 171, 106, 90);
const southEnd = blob("South End Dump Run", 50, 161, 113, 190);
const endZone = blob("End Zone", 100, 68, 0, 300);

(function testRealChuteDimensionsAreWideAndShort() {
  const G = QGeo.geom(afterPride);
  assert(Math.abs(G.L - 111) < 2 && afterPride.widthM === 75, "After Pride fixture is the real 75 m x 111 m blob, got L=" + G.L);
})();

(function testTraverseAcrossEachRealChuteIsNotARun() {
  [afterPride, alley17, southEnd, endZone].forEach(c => {
    const P = alongPath(c), [lat0, lon0] = posAt(P, 0.5 * P.L), out = [];
    const span = c.widthM / 2 + 12, n = Math.ceil(2 * span / 3.7);
    for (let i = 0; i <= n; i++) out.push({ lat: lat0, lon: lon0 + (-span + 2 * span * i / n) / QGeo.mPerDegLat * 1.6, t: BASE + i * 1000, speed: 3.7, acc: 8, alt: null });
    assert(classify(c, out, "ski", QGeo, QUEST_TUNING) === undefined, "a ~4 m/s traverse across " + c.name + " (" + c.widthM + " m wide) must not log, as it did in the field");
  });
})();

(function testFieldLogShapedCornerCutsAreRejected() {
  // The logged runs were 49-65 m of travel through a 111-171 m corridor: less
  // than the ~55-90 m along the corridor that reaching both end zones needs.
  [[afterPride, 49, 4.7], [alley17, 60, 3.7], [southEnd, 65, 3.8]].forEach(([c, dist, v]) => {
    const t = mkTrack(c, { from: 0.25, to: 0.25 + dist / QGeo.geom(c).L, speed: v, noiseM: 4 });
    assert(classify(c, t, "ski", QGeo, QUEST_TUNING) === undefined, c.name + ": " + dist + " m of travel in the middle of the corridor isn't a run");
  });
})();

(function testThreeAdjacentRealChutesTraversedInOneGoLogNothing() {
  const cs = [afterPride, alley17, southEnd];
  const { Q, logged } = makeQuest(cs);
  const P = alongPath(alley17), [lat0] = posAt(P, 0.5 * P.L), out = [];
  for (let i = 0; i <= 90; i++) out.push({ lat: lat0, lon: -117.05 - 60 / QGeo.mPerDegLon(lat0) + i * (330 / 90) / QGeo.mPerDegLon(lat0), t: BASE + i * 1000, speed: 3.7, acc: 8, alt: null });
  out.forEach(fx => cs.forEach(c => tickFn.call(Q, c, fx, "ski", QGeo, QUEST_TUNING)));
  out.push({ lat: 51.31, lon: -117.03, t: BASE + 900000, speed: 3, acc: 8, alt: null });
  cs.forEach(c => tickFn.call(Q, c, out[out.length - 1], "ski", QGeo, QUEST_TUNING));
  assert(logged.length === 0, "the reported scenario -- one traverse across 3 chutes -- logs none of them, got " + JSON.stringify(logged.map(r => r.runName)));
})();

(function testRealDescentOfAfterPrideStillCounts() {
  const run = classify(afterPride, mkTrack(afterPride, { speed: 6, noiseM: 10, acc: 10 }), "ski", QGeo, QUEST_TUNING);
  assert(run && run.activity === "ski" && run.verticalM < -60, "skiing After Pride top to bottom (10 m wobble) counts and scores its authored descent, got " + JSON.stringify(run && { a: run.activity, v: run.verticalM }));
})();

(function testFastRealDescentOfShortChuteStillCounts() {
  // ~11 m/s down 111 m: only a few seconds between the two end zones. The old
  // 8 s minimum would have thrown this genuine run away.
  const run = classify(afterPride, mkTrack(afterPride, { speed: 11, dt: 0.5 }), "ski", QGeo, QUEST_TUNING);
  assert(run && run.activity === "ski", "a fast (11 m/s) descent of a 111 m chute counts, got " + JSON.stringify(run && run.activity));
})();

(function testDiagonalTraverseAtConstantAltitudeIsRejectedByElevation() {
  // A diagonal cut through the whole blob at constant height (a real traverse):
  // geometry alone can't tell it from a descent -- the elevation check does.
  const P = alongPath(afterPride), out = [];
  for (let i = 0; i <= 30; i++) {
    const s = 8 + (95 * i) / 30, off = 28 - (56 * i) / 30, [lat, lon] = posAt(P, s);
    out.push({ lat, lon: lon + off / QGeo.mPerDegLon(lat), t: BASE + i * 3000, speed: 1.1, acc: 8, alt: 2000 + Math.sin(i) * 2 });
  }
  const fb = [];
  const run = classify.call({ onCoverage: (n, p, ok, why) => fb.push({ ok, why }) }, afterPride, out, "hike", QGeo, QUEST_TUNING);
  const asHike = run && run.activity;
  assert(run === undefined, "a constant-altitude diagonal through After Pride is a traverse, not a descent, got " + JSON.stringify(asHike));
  assert(fb.length === 1 && /elevation/.test(fb[0].why), "and the player is told the elevation didn't match, got " + JSON.stringify(fb));
  // the SAME line while actually dropping ~70 m is a real (diagonal) descent
  const dropping = out.map((fx, i) => Object.assign({}, fx, { alt: 2070 - 70 * (i / 30) }));
  const real = classify(afterPride, dropping, "hike", QGeo, QUEST_TUNING);
  // (a descended chute is ski by the 2026-09-17 rule, whatever the pace)
  assert(real && real.activity === "ski", "the same line with a real ~70 m drop counts, got " + JSON.stringify(real && real.activity));
})();


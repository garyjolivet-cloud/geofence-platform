const BASE = 1700000000000;
// Positions along a corridor by arc length (m from path[0]).
function alongPath(c) {
  const cum = [0];
  for (let i = 1; i < c.path.length; i++) cum.push(cum[i - 1] + QGeo.haversineM(c.path[i - 1], c.path[i]));
  return { pts: c.path, cum, L: cum[cum.length - 1] };
}
function posAt(P, s) {
  s = Math.max(0, Math.min(P.L, s));
  let i = 1; while (i < P.cum.length - 1 && P.cum[i] < s) i++;
  const f = (s - P.cum[i - 1]) / (P.cum[i] - P.cum[i - 1]), a = P.pts[i - 1], b = P.pts[i];
  return [a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f];
}
// A realistic fix stream: walks fraction `from`->`to` of the corridor (0 = top)
// at `speed` m/s, one fix per `dt` s, optional lateral offset/noise (m, east).
function mkTrack(c, o) {
  o = Object.assign({ from: 0, to: 1, speed: 6, dt: 1, lateralM: 0, noiseM: 0, acc: 8, t0: 0, alt0: null, alt1: null }, o);
  const P = alongPath(c), s0 = o.from * P.L, s1 = o.to * P.L;
  const n = Math.max(1, Math.ceil(Math.abs(s1 - s0) / o.speed / o.dt));
  const out = [];
  for (let i = 0; i <= n; i++) {
    const f = i / n;
    let [lat, lon] = posAt(P, s0 + (s1 - s0) * f);
    lon += (o.lateralM + o.noiseM * Math.sin(i * 1.7 + 1)) / QGeo.mPerDegLon(lat);
    lat += (o.noiseM * 0.5 * Math.sin(i * 2.3)) / QGeo.mPerDegLat;
    out.push({ lat, lon, t: BASE + (o.t0 + i * o.dt) * 1000, speed: o.speed, acc: o.acc,
      alt: o.alt0 != null ? o.alt0 + (o.alt1 - o.alt0) * f : null });
  }
  return out;
}
// A straight east-west crossing of the corridor at fraction `at`, +-spanM.
function mkCross(c, at, o) {
  o = Object.assign({ spanM: 100, speed: 1.5, dt: 1, acc: 8, t0: 0 }, o);
  const P = alongPath(c), [lat0, lon0] = posAt(P, at * P.L);
  const n = Math.ceil(2 * o.spanM / o.speed / o.dt), out = [];
  for (let i = 0; i <= n; i++) {
    const off = -o.spanM + (2 * o.spanM) * (i / n);
    out.push({ lat: lat0, lon: lon0 + off / QGeo.mPerDegLon(lat0), t: BASE + (o.t0 + i * o.dt) * 1000, speed: o.speed, acc: o.acc, alt: null });
  }
  return out;
}
const last = a => a[a.length - 1];
const tEnd = a => (last(a).t - BASE) / 1000;


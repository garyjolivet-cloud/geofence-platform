// Unit tests for Ridge Quest's corridor-run detector in frontend/ridge-quest.html:
//   - QGeo.corridorDist / projectOnPath (signed-distance + along-corridor math)
//   - QGeo.evaluateTraversal, via Quest._classifyAndLog: does a recorded track
//     amount to a real END-TO-END pass of a corridor (start/end zones in order,
//     bin coverage, off-route, direction/bearing, speed/time, elevation)?
//   - the classification that follows (ski/lift/hike/bike/xcski/drive)
//   - Quest._tick: the narration band AND the run recorder that drives logging
//
// 2026-09-21 field report that motivated the rewrite: skiing ACROSS corridors
// (a traverse) logged them as skied. The old test fixtures fed physically
// impossible tracks (a 1.1 km jump in 2 s with speed:1), which is exactly why
// nothing caught it -- every track here is generated by walking a real path at
// a real speed (mkTrack).
//
// Extracts the real QGeo/QUEST_TUNING and the real method bodies straight out
// of the shipped file, so this tests the code that ships, not a
// reimplementation (same technique as tests/cylinder-segment-cross.test.js).
// The trailing api() POST in _classifyAndLog needs a live session/fetch and
// belongs to a manual on-mountain test.
//
// Run: `node --test tests/quest-corridor-detection.test.js` (or as part of the
// full `node --test tests/` suite).
"use strict";
const fs = require("fs");
const path = require("path");

let pass = 0, fail = 0;
function assert(cond, msg) { if (cond) pass++; else { fail++; console.log("FAIL:", msg); } }

const html = fs.readFileSync(path.join(__dirname, "../frontend/ridge-quest.html"), "utf8");

// ---- extract QGeo + QUEST_TUNING ----
const qgeoM = html.match(/const QGeo = \{[\s\S]*?\n\};/);
if (!qgeoM) { console.log("FAIL: could not extract QGeo from ridge-quest.html"); process.exit(1); }
const QGeo = eval("(" + qgeoM[0].replace(/^const QGeo = /, "").replace(/;$/, "") + ")");
const tuningM = html.match(/const QUEST_TUNING = \{[\s\S]*?\n\};/);
if (!tuningM) { console.log("FAIL: could not extract QUEST_TUNING from ridge-quest.html"); process.exit(1); }
const QUEST_TUNING = eval("(" + tuningM[0].replace(/^const QUEST_TUNING = /, "").replace(/;$/, "") + ")");

// ---- extract Quest._classifyAndLog's body, stopping before the api() POST ----
const startTag = "_classifyAndLog(corridor, buffer, selectedActivity, isFinal){";
const startIdx = html.indexOf(startTag);
if (startIdx < 0) { console.log("FAIL: could not find _classifyAndLog in ridge-quest.html"); process.exit(1); }
const endTag = "\n    api(\"/api/quest-runs\"";
const endIdx = html.indexOf(endTag, startIdx);
if (endIdx < 0) { console.log("FAIL: could not find end of _classifyAndLog body in ridge-quest.html"); process.exit(1); }
// eslint-disable-next-line no-new-func
const classifyRaw = new Function("corridor", "buffer", "selectedActivity", "isFinal", "QGeo", "QUEST_TUNING",
  html.slice(startIdx + startTag.length, endIdx) + "\nreturn run;");
// Old call shape (corridor, buffer, activity, QGeo, QUEST_TUNING), as a
// player who has LEFT the corridor (isFinal). Returns the run, or undefined.
function classify(corridor, buffer, sel, QG, QT) {
  const r = classifyRaw.call(this, corridor, buffer, sel, true, QG, QT);
  return (r && typeof r === "object") ? r : undefined;
}

// ---- extract Quest._tick's body by brace matching ----
function extractMethodBody(tag) {
  const s = html.indexOf(tag);
  if (s < 0) { console.log("FAIL: could not find " + tag); process.exit(1); }
  let depth = 0, i = html.indexOf("{", s); const bodyStart = i + 1;
  for (; i < html.length; i++) {
    if (html[i] === "{") depth++;
    else if (html[i] === "}") { depth--; if (depth === 0) break; }
  }
  return html.slice(bodyStart, i);
}
// eslint-disable-next-line no-new-func
const tickFn = new Function("corridor", "p", "selectedActivity", "QGeo", "QUEST_TUNING",
  extractMethodBody("_tick(corridor, p, selectedActivity){"));

// A Quest stand-in wired to the REAL _tick and REAL _classifyAndLog.
function makeQuest(corridors) {
  const logged = [], feedback = [];
  const Q = {
    states: {}, corridors, selectedActivity: "ski", onNarrate: null,
    onCoverage: (name, pct, passed, reason) => feedback.push({ name, pct, passed, reason }),
    _classifyAndLog(c, b, s, isFinal) {
      const r = classifyRaw.call(Q, c, b, s, isFinal, QGeo, QUEST_TUNING);
      if (r && typeof r === "object") { logged.push(r); return true; }
      return r;
    }
  };
  return { Q, logged, feedback };
}
function feed(Q, corridor, fixes, sel) {
  fixes.forEach(f => tickFn.call(Q, corridor, f, sel || "ski", QGeo, QUEST_TUNING));
}

